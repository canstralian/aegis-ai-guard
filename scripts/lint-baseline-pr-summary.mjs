#!/usr/bin/env node
/**
 * Builds a Markdown summary of lint-baseline changes for a PR comment.
 *
 * - Diffs supabase/lint-baseline.json between BASE_SHA and HEAD_SHA
 * - Extracts new entries appended to supabase/lint-baseline.log.md
 * - Writes the result to lint-baseline-comment.md
 * - Sets a `body` GitHub Actions output (empty if no relevant changes)
 */
import { execSync } from "node:child_process";
import { writeFileSync, appendFileSync, readFileSync, existsSync } from "node:fs";

const BASE = process.env.BASE_SHA;
const HEAD = process.env.HEAD_SHA || "HEAD";
const BASELINE = "supabase/lint-baseline.json";
const LOG = "supabase/lint-baseline.log.md";
const REGISTRY = "supabase/lint-monitored-codes.json";

const labels = {};
if (existsSync(REGISTRY)) {
  try {
    for (const entry of JSON.parse(readFileSync(REGISTRY, "utf8")).codes ?? []) {
      labels[entry.code] = entry.label || entry.name || entry.code;
    }
  } catch {}
}

if (!BASE) {
  console.error("BASE_SHA env var required");
  process.exit(2);
}

function show(ref, path) {
  try {
    return execSync(`git show ${ref}:${path}`, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    return null;
  }
}

function parseBaseline(text) {
  if (!text) return {};
  try {
    return JSON.parse(text).codes || {};
  } catch {
    return {};
  }
}

const baseCodes = parseBaseline(show(BASE, BASELINE));
const headCodes = parseBaseline(show(HEAD, BASELINE));

const allCodes = new Set([...Object.keys(baseCodes), ...Object.keys(headCodes)]);
const changedRows = [];
for (const code of allCodes) {
  const before = baseCodes[code] ?? "—";
  const after = headCodes[code] ?? "—";
  if (before !== after) {
    const arrow = before === "—" ? "🆕" : after === "—" ? "🗑️" : after > before ? "🔺" : "🔻";
    const label = labels[code] ? ` <sub>${labels[code]}</sub>` : "";
    changedRows.push(`| \`${code}\`${label} | ${before} | ${after} | ${arrow} |`);
  }
}

// Diff log file: lines added in HEAD vs BASE
let logDiff = "";
try {
  logDiff = execSync(`git diff ${BASE}..${HEAD} -- ${LOG}`, { encoding: "utf8" });
} catch {}
const newLogLines = logDiff
  .split("\n")
  .filter((l) => l.startsWith("+") && !l.startsWith("+++"))
  .map((l) => l.slice(1))
  .join("\n")
  .trim();

if (changedRows.length === 0 && !newLogLines) {
  console.log("No lint-baseline changes to report.");
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, "body=\n");
  process.exit(0);
}

let body = `## 🛡️ Supabase Lint Baseline Change\n\n`;
body += `This PR modifies the accepted-warning baseline tracked by the DB linter CI guard.\n\n`;

if (changedRows.length) {
  body += `### Code count changes\n\n`;
  body += `| Lint code | Before | After | |\n|---|---:|---:|---|\n`;
  body += changedRows.join("\n") + "\n\n";
}

if (newLogLines) {
  body += `### New justification log entries\n\n`;
  body += "```markdown\n" + newLogLines + "\n```\n\n";
} else {
  body += `> ⚠️ Baseline counts changed but no new justification was added to \`${LOG}\`. ` +
    `Reviewers should request justification before merging.\n\n`;
}

body += `---\n`;
body += `_Generated by \`lint-baseline-comment.yml\`. Compare \`supabase/lint-baseline.json\` to confirm intent._\n`;

writeFileSync("lint-baseline-comment.md", body);
console.log(body);

if (process.env.GITHUB_OUTPUT) {
  // Use a delimiter to safely emit multi-line output
  const delim = `EOF_${Date.now()}`;
  appendFileSync(process.env.GITHUB_OUTPUT, `body<<${delim}\n${body}\n${delim}\n`);
}
